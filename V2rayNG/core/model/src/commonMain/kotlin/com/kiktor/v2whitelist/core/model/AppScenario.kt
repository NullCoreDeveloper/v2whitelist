package com.kiktor.v2whitelist.core.model

/**
 * Сценарии работы приложения для автоматического и ручного отбора узлов.
 */
enum class AppScenario {
    AUTO,          // Автоматический выбор под текущее состояние сети (БС при глушилках, ЧС/YouTube при обычной сети)
    VPN_BLACKLIST, // Обход блокировок (Черные списки)
    WHITELIST,     // Режим белых списков РФ
    YOUTUBE,       // YouTube и медиа-сервисы
    KEEP_CURRENT   // Без принудительной фильтрации сценариев
}
